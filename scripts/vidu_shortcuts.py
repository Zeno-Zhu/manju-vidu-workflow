"""vidu_shortcuts.py —— 生成「Vidu 账号N」一键启动器 ＋ 桌面快捷方式（★ 纯 Python，不依赖 Node）。

> 原实现是 `vidu_shortcuts.py`（要 Node）。改 Python 是为了让整个包**只依赖
> Python ＋ websocket-client ＋ Edge** —— 分发/开源场景下少一个前置条件。

为什么这么写（windows-zh-launcher 四条铁律）：
  1) `.cmd` 必须 **CRLF** —— 否则 cmd 只"半懂"，括号块被拆、报一堆莫名错误
  2) `.cmd` 内容**只用 ASCII** —— 中文在 GBK 控制台变乱码
     ★ 所以账号用**序号**传（`--account-index N`），中文名不进 .cmd
  3) 中文文件名 / `.lnk` 交给 COM(WScript.Shell)，PowerShell 必须 `-EncodedCommand`
     （否则中文参数在 cmd 传参层就被 GBK 吃掉）
  4) 真源（本文件）与产物（`.cmd` / `.lnk`）分离，生成器**幂等**、可重跑

用法：
  python vidu_shortcuts.py                      # 默认 = 账号1
  python vidu_shortcuts.py --account-index 2    # 账号2（端口 9223、独立 profile）
  python vidu_shortcuts.py --account-index 2 --no-lnk   # 只刷 .cmd，不碰桌面

产物（示例：账号2）：
  ~/.manju-vidu/vidu-open-a2.cmd / vidu-close-a2.cmd
  桌面\\Vidu 账号2 - 启动.lnk / Vidu 账号2 - 关闭.lnk
  （账号1 额外生成旧名 vidu-open.cmd / vidu-close.cmd 作兼容别名）
"""
from __future__ import annotations

import argparse
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
PY = sys.executable                                    # ★ 用当前解释器，别写死路径
EDGE = r"C:\Program Files (x86)\Microsoft\Edge\Application\msedge.exe"
EDGE64 = r"C:\Program Files\Microsoft\Edge\Application\msedge.exe"
CH_DIR = os.path.join(os.path.expanduser("~"), ".manju-vidu")
VIDEO_EDGE = os.path.join(HERE, "vidu_edge.py")

BANNER_OPEN = """@echo off
setlocal
rem ===============================================================
rem  Vidu channel launcher  (source: scripts/vidu_shortcuts.py)
rem  account = {acc}   cdp port = {port}
rem  ASCII only + CRLF. Do NOT edit this file by hand.
rem  Starts / reuses THIS ACCOUNT's dedicated automation Edge profile
rem  and opens the Vidu creation page.
rem  Never touches your everyday Edge profile.
rem ===============================================================
set "PY={py}"
set "EDGE_SCRIPT={edge_script}"
if not exist "%PY%" (
  echo [ERROR] python not found:
  echo         %PY%
  echo         Edit PY in this file.
  pause
  exit /b 1
)
if not exist "%EDGE_SCRIPT%" (
  echo [ERROR] vidu_edge.py not found:
  echo         %EDGE_SCRIPT%
  pause
  exit /b 1
)
echo [--] bringing up Vidu instance (account {acc}, port {port}) ...
"%PY%" "%EDGE_SCRIPT%" up --account-index {acc} --wait 60
if errorlevel 1 (
  echo.
  echo [ERROR] launch failed. See the messages above.
  pause
  exit /b 1
)
echo.
echo [OK] ready. If it says "not logged in", sign in inside that window,
echo      then close it - the cookie is kept in this account's profile.
ping -n 3 -w 1000 127.0.0.1 >nul
exit /b 0
"""

BANNER_CLOSE = """@echo off
setlocal
rem ===============================================================
rem  Vidu channel closer   (source: scripts/vidu_shortcuts.py)
rem  account = {acc}   cdp port = {port}
rem  Gracefully closes THIS ACCOUNT's automation Edge instance via
rem  CDP Browser.close, so cookies are flushed to its profile.
rem  ASCII only + CRLF. Do NOT edit this file by hand.
rem ===============================================================
set "PY={py}"
set "EDGE_SCRIPT={edge_script}"
if not exist "%PY%" (
  echo [ERROR] python not found: %PY%
  pause
  exit /b 1
)
"%PY%" "%EDGE_SCRIPT%" down --account-index {acc}
if errorlevel 1 (
  echo.
  echo [ERROR] graceful close failed.
  pause
  exit /b 1
)
echo [OK] Vidu instance (account {acc}) closed.
ping -n 2 -w 1000 127.0.0.1 >nul
exit /b 0
"""

BANNER_ALIAS = """@echo off
rem legacy entry name - kept so old habits still work. Real body: vidu-open-a{acc}.cmd
call "%~dp0vidu-open-a{acc}.cmd" %*
"""


def write_cmd(name, body):
    """写 .cmd：**ASCII + CRLF**；内容未变则不重写（幂等）。"""
    dest = os.path.join(CH_DIR, name)
    os.makedirs(CH_DIR, exist_ok=True)
    data = body.replace("\r\n", "\n").replace("\n", "\r\n")
    try:
        if os.path.exists(dest):
            with open(dest, "rb") as f:
                if f.read() == data.encode("ascii"):
                    print("= unchanged  %s" % dest)
                    return dest
        with open(dest, "wb") as f:
            f.write(data.encode("ascii"))
        print("+ written    %s" % dest)
    except UnicodeEncodeError as e:
        print("!! 内容含非 ASCII 字符，无法写入 .cmd: %s" % e)
    return dest


def ps_encoded(script):
    """PowerShell 必须 -EncodedCommand（UTF-16LE + base64），否则中文参数被 GBK 吃掉。"""
    preamble = "[Console]::OutputEncoding = [System.Text.Encoding]::UTF8\n"
    import base64
    return base64.b64encode((preamble + script).encode("utf-16le")).decode("ascii")


def make_shortcuts(items, icon):
    rows = ",\n  ".join(
        "@{name='%s'; cmd='%s'; wd='%s'; desc='%s'}" % (it["name"], it["cmd"], it["wd"], it["desc"])
        for it in items)
    script = """
$ErrorActionPreference = 'Stop'
$desktop = [Environment]::GetFolderPath('Desktop')
$shell = New-Object -ComObject WScript.Shell
$items = @(
  %s
)
foreach ($it in $items) {
  $lnk = Join-Path $desktop $it.name
  $s = $shell.CreateShortcut($lnk)
  $s.TargetPath = "$env:SystemRoot\\System32\\cmd.exe"
  $s.Arguments  = '/c "' + $it.cmd + '"'
  $s.WorkingDirectory = $it.wd
  $s.IconLocation = '%s,0'
  $s.WindowStyle = 1
  $s.Description = $it.desc
  $s.Save()
}
foreach ($it in $items) {
  $lnk = Join-Path $desktop $it.name
  $c = $shell.CreateShortcut($lnk)
  $exists = Test-Path -LiteralPath $it.cmd
  Write-Output ("LNK=" + $it.name + "|ARGS=" + $c.Arguments + "|CMDEXISTS=" + $exists)
}
""" % (rows, icon)
    try:
        out = subprocess.run(
            ["powershell.exe", "-NoProfile", "-NonInteractive",
             "-OutputFormat", "Text", "-EncodedCommand", ps_encoded(script)],
            capture_output=True, text=True, encoding="utf-8", errors="replace", timeout=120)
    except Exception as e:
        return ["(生成快捷方式失败：%s)" % str(e)[:120]]
    txt = (out.stdout or "") + (out.stderr or "")
    lines = []
    for ln in txt.splitlines():
        ln = ln.strip()
        # 滤掉 PowerShell 的 CLIXML 进度噪声，只留我们自己的校验行
        if ln.startswith("LNK="):
            lines.append(ln)
    return lines or ["(未收到校验行；请手动确认桌面是否有快捷方式)"]


def main():
    ap = argparse.ArgumentParser(description="生成 Vidu 账号启动器 + 桌面快捷方式")
    ap.add_argument("--account-index", type=int, default=1, help="账号序号（端口 9221+N）")
    ap.add_argument("--no-lnk", action="store_true", help="只刷 .cmd，不碰桌面")
    a = ap.parse_args()
    acc, tag, label = a.account_index, "a%d" % a.account_index, "账号%d" % a.account_index
    port = 9221 + acc

    fmt = dict(py=PY, edge_script=VIDEO_EDGE, acc=acc, port=port)
    open_cmd = write_cmd("vidu-open-%s.cmd" % tag, BANNER_OPEN.format(**fmt))
    close_cmd = write_cmd("vidu-close-%s.cmd" % tag, BANNER_CLOSE.format(**fmt))
    write_cmd("start-vidu-edge-%s.cmd" % tag, BANNER_ALIAS.format(acc=acc))
    if acc == 1:      # 账号1 保留旧名，老习惯继续可用
        write_cmd("vidu-open.cmd", BANNER_OPEN.format(**fmt))
        write_cmd("vidu-close.cmd", BANNER_CLOSE.format(**fmt))
        write_cmd("start-vidu-edge.cmd", BANNER_ALIAS.format(acc=acc))

    if a.no_lnk:
        print("\n(--no-lnk) 桌面快捷方式未改动。")
        return 0

    icon = EDGE if os.path.exists(EDGE) else (EDGE64 if os.path.exists(EDGE64) else "cmd.exe")
    print("\n创建桌面快捷方式（%s，端口 %d）…" % (label, port))
    for r in make_shortcuts([
        {"name": "Vidu %s - 启动.lnk" % label, "cmd": open_cmd, "wd": CH_DIR,
         "desc": "Start / wake the Vidu Edge instance of %s" % label},
        {"name": "Vidu %s - 关闭.lnk" % label, "cmd": close_cmd, "wd": CH_DIR,
         "desc": "Gracefully close the Vidu Edge instance of %s" % label},
    ], icon):
        print("  " + r)
    print("\nOK. 桌面快捷方式就绪。")
    return 0


if __name__ == "__main__":
    sys.exit(main())
